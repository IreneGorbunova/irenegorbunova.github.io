/**
 * The constellations of «Моё небо». Every section of the textbook is one real constellation; the stars, in `stars` order,
 * are cut into consecutive blocks, one block per chapter of the section (sizes differ by at most one), so chapters can be
 * added, merged or dropped freely. A chapter lights the share of its block equal to the share of its steps that are done
 * (progress.ts).
 * Stars: J2000 positions and V magnitudes from the Yale Bright Star Catalogue, 5th ed. (HR numbers in the comments);
 * projected gnomonically around `center`, east to the left, north up — as seen in the sky.
 * Figures: Hevelius' «Uranographia» (1690, public domain), scans of ETH-Bibliothek Zürich (e-rara). Hevelius drew the sky
 * as on a celestial globe seen from outside, so each plate is mirrored, then warped onto the real stars (a fit of his
 * ecliptic grid to 25–85 catalogue stars per plate); the webp is already in the sky frame of `project()`, `box` gives its
 * corners there. Tools and fits: /storage/arsenii/ig_webpage/review/sky/tools.
 * Generated by gen_ts.py there; edit the data in spec.py / facts.py and regenerate.
 */

export interface Star {
	id: string;
	name: string;
	ra: number; // hours
	dec: number; // degrees
	mag: number;
}
export interface Constellation {
	name: string;
	fact: string;
	stars: Star[];
	lines: [string, string][];
	center: { ra: number; dec: number };
	/** Hevelius' figure, already in the projected sky frame: box = [x0, y0, x1, y1] of the image there */
	art?: { file: string; box: [number, number, number, number]; plate: string };
}

